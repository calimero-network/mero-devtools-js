/**
 * Kotlin client generation: kotlinx.serialization types for every ABI type and
 * a client with one suspend function per method, over a transport interface
 * declared in the same file so the output has no SDK dependency.
 */
import {
  AbiField,
  AbiManifest,
  AbiMethod,
  AbiTypeDef,
  AbiVariant,
  AbiVariantDef,
} from '../model.js';
import { sanitizeClassName } from './emit.js';
import {
  docLines,
  hasReturnValue,
  lowerCamel,
  methodNotes,
  methodRoute,
  NativeSyntax,
  NativeTypes,
  typeName,
  upperCamel,
  variantStyle,
} from './native.js';

const BANNER = '// @generated by @calimero/abi-codegen — DO NOT EDIT.';
const TUPLE_FIELDS = ['first', 'second', 'third', 'fourth', 'fifth', 'sixth'];

// Hard keywords, which need backticks as identifiers.
const RESERVED = new Set([
  'as',
  'break',
  'class',
  'continue',
  'do',
  'else',
  'false',
  'for',
  'fun',
  'if',
  'in',
  'interface',
  'is',
  'null',
  'object',
  'package',
  'return',
  'super',
  'this',
  'throw',
  'true',
  'try',
  'typealias',
  'typeof',
  'val',
  'var',
  'when',
  'while',
]);

const IMPORTS = [
  'kotlinx.serialization.KSerializer',
  'kotlinx.serialization.SerialName',
  'kotlinx.serialization.Serializable',
  'kotlinx.serialization.SerializationException',
  'kotlinx.serialization.descriptors.SerialDescriptor',
  'kotlinx.serialization.encoding.Decoder',
  'kotlinx.serialization.encoding.Encoder',
  'kotlinx.serialization.json.Json',
  'kotlinx.serialization.json.JsonArray',
  'kotlinx.serialization.json.JsonDecoder',
  'kotlinx.serialization.json.JsonElement',
  'kotlinx.serialization.json.JsonEncoder',
  'kotlinx.serialization.json.JsonNull',
  'kotlinx.serialization.json.JsonObject',
  'kotlinx.serialization.json.JsonPrimitive',
  'kotlinx.serialization.json.jsonArray',
  'kotlinx.serialization.json.jsonObject',
  'kotlinx.serialization.json.jsonPrimitive',
  'kotlinx.serialization.serializer',
];

const KOTLIN: NativeSyntax = {
  scalars: {
    bool: 'Boolean',
    i32: 'Int',
    i64: 'Long',
    u32: 'UInt',
    u64: 'ULong',
    f32: 'Float',
    f64: 'Double',
    string: 'String',
  },
  rustScalars: {
    String: 'String',
    bool: 'Boolean',
    u8: 'UByte',
    u16: 'UShort',
    u32: 'UInt',
    u64: 'ULong',
    i8: 'Byte',
    i16: 'Short',
    i32: 'Int',
    i64: 'Long',
    f32: 'Float',
    f64: 'Double',
  },
  // serde's unit is `null` on the wire; JsonElement carries it as JsonNull.
  unit: 'JsonElement',
  // A JSON array of numbers, as the TS client sends bytes. ByteArray would
  // encode signed values, so 0xff would go out as -1.
  bytes: 'List<UByte>',
  fixedBytes: 'String',
  list: (item) => `List<${item}>`,
  map: (key, value) => `Map<${key}, ${value}>`,
  optional: (type) => (type.endsWith('?') ? type : `${type}?`),
  tuple: (elements) =>
    `ContractTuple${elements.length}<${elements.join(', ')}>`,
};

function ident(name: string): string {
  return RESERVED.has(name) ? `\`${name}\`` : name;
}

function kotlinString(text: string): string {
  const escaped = text
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\$/g, '\\$')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t')
    .replace(
      /[\u0000-\u001f]/g,
      (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`,
    );
  return `"${escaped}"`;
}

// KDoc. A literal `*/` would close the comment, so it is escaped as in the TS
// target; Kotlin comments nest, so a literal `/*` would open another one.
function docComment(doc: string | undefined, indent: string): string[] {
  if (!doc) return [];
  const lines = docLines(doc.replace(/\*\//g, '*\\/').replace(/\/\*/g, '/\\*'));
  if (lines.length === 1) return [`${indent}/** ${lines[0]} */`];
  return [
    `${indent}/**`,
    ...lines.map((line) => (line ? `${indent} * ${line}` : `${indent} *`)),
    `${indent} */`,
  ];
}

/**
 * Generate a Kotlin client from a WASM-ABI v1 manifest
 * @param manifest - The parsed ABI manifest
 * @param clientName - The name of the generated client class
 * @param packageName - The file's package; omitted when not given
 * @returns Generated Kotlin source as a string
 */
export function generateKotlinClient(
  manifest: AbiManifest,
  clientName: string = 'Client',
  packageName?: string,
): string {
  clientName = sanitizeClassName(clientName);
  const types = new NativeTypes(manifest, KOTLIN);

  const typeBlocks: string[][] = [];
  for (const [name, def] of Object.entries(manifest.types)) {
    typeBlocks.push(typeDefinition(typeName(name), def, types));
  }
  const client = clientClass(clientName, manifest, types);
  // Inline records are found while mapping, and may hold further inline records.
  for (let i = 0; i < types.inlineRecords.length; i++) {
    const { name, record } = types.inlineRecords[i];
    typeBlocks.push(dataClass(name, record.fields, record.doc, types));
  }

  const lines: string[] = [BANNER, ''];
  if (packageName) lines.push(`package ${packageName}`, '');
  lines.push(...IMPORTS.map((i) => `import ${i}`), '');
  lines.push(...transportInterface(), '');
  lines.push(...client, '');
  for (const block of typeBlocks) lines.push(...block, '');
  for (const arity of [...types.tupleArities].sort((a, b) => a - b)) {
    lines.push(...tupleClass(arity), '');
  }
  return lines.join('\n').trimEnd() + '\n';
}

function transportInterface(): string[] {
  return [
    '/**',
    " * Carries one call to a context and returns the method's JSON result.",
    ' *',
    ' * [query] runs a view (a method the app declared `read_only`) and [execute]',
    ' * runs everything else. Both take the arguments as a JSON object and return',
    ' * the JSON the method produced.',
    ' */',
    'interface ContextContractCalling {',
    '    suspend fun query(method: String, argsJson: String): String',
    '',
    '    suspend fun execute(method: String, argsJson: String): String',
    '}',
  ];
}

function typeDefinition(
  name: string,
  def: AbiTypeDef,
  types: NativeTypes,
): string[] {
  switch (def.kind) {
    case 'record':
      if (def.crdt_type && def.inner_type) {
        return [
          ...docComment(def.doc, ''),
          `typealias ${name} = ${types.typeRef(def.inner_type, name)}`,
        ];
      }
      return dataClass(name, def.fields, def.doc, types);
    case 'variant':
      return sealedOrEnum(name, def, types);
    case 'alias': {
      const doc = [
        def.doc,
        def.pattern && `Values match \`${def.pattern}\` (not checked here).`,
      ]
        .filter(Boolean)
        .join('\n\n');
      return [
        ...docComment(doc, ''),
        `typealias ${name} = ${types.typeRef(def.target, name)}`,
      ];
    }
    case 'bytes': {
      const size =
        'size' in def
          ? `${def.size} bytes, as the contract's own text (base58 or hex).`
          : undefined;
      return [
        ...docComment(size, ''),
        `typealias ${name} = ${types.typeRef(def, name)}`,
      ];
    }
  }
}

// One constructor parameter; a nullable one defaults to null, so it is left
// out of the encoded object when null (kotlinx skips default values).
function property(
  wire: string,
  type: string,
  nullable: boolean | undefined,
  doc: string | undefined,
  indent: string,
): string[] {
  const name = lowerCamel(wire);
  const fullType = nullable ? KOTLIN.optional(type) : type;
  const serialName = name === wire ? '' : `@SerialName(${kotlinString(wire)}) `;
  return [
    ...docComment(doc, indent),
    `${indent}${serialName}val ${ident(name)}: ${fullType}${fullType.endsWith('?') ? ' = null' : ''},`,
  ];
}

function dataClass(
  name: string,
  fields: AbiField[],
  doc: string | undefined,
  types: NativeTypes,
): string[] {
  const lines = [...docComment(doc, ''), '@Serializable'];
  if (fields.length === 0) {
    // A data class needs a property; an empty record is `{}` on the wire.
    lines.push(
      `class ${name} {`,
      `    override fun equals(other: Any?): Boolean = other is ${name}`,
      '',
      `    override fun hashCode(): Int = ${kotlinString(name)}.hashCode()`,
      '}',
    );
    return lines;
  }
  lines.push(`data class ${name}(`);
  for (const field of fields) {
    lines.push(
      ...property(
        field.name,
        types.typeRef(field.type, `${name}${upperCamel(field.name)}`),
        field.nullable,
        field.doc,
        '    ',
      ),
    );
  }
  lines.push(')');
  return lines;
}

interface Case {
  variant: AbiVariant;
  name: string;
  payload?: string;
}

function sealedOrEnum(
  name: string,
  def: AbiVariantDef,
  types: NativeTypes,
): string[] {
  const style = variantStyle(def);
  const cases: Case[] = def.variants.map((variant) => ({
    variant,
    name: upperCamel(variant.name),
    payload:
      variant.payload && !NativeTypes.isUnit(variant.payload)
        ? types.typeRef(variant.payload, `${name}${upperCamel(variant.name)}`)
        : undefined,
  }));

  const lines = [...docComment(def.doc, '')];
  if (style === 'unit') {
    // serde writes a payload-free enum as the bare variant name.
    lines.push('@Serializable', `enum class ${name} {`);
    for (const c of cases) {
      lines.push(
        ...docComment(c.variant.doc, '    '),
        `    @SerialName(${kotlinString(c.variant.name)})`,
        `    ${ident(c.name)},`,
      );
    }
    lines.push('}');
    return lines;
  }

  const serializerName = `${name}Serializer`;
  lines.push(
    `@Serializable(with = ${serializerName}::class)`,
    `sealed class ${name} {`,
  );
  cases.forEach((c, i) => {
    if (i > 0) lines.push('');
    lines.push(...docComment(c.variant.doc, '    '));
    lines.push(
      c.payload
        ? `    data class ${c.name}(val value: ${c.payload}) : ${name}()`
        : `    object ${c.name} : ${name}()`,
    );
  });
  lines.push('}', '');

  const ref = (c: Case) => `${name}.${c.name}`;
  const encode = (c: Case) =>
    `json.encodeToJsonElement(serializer<${c.payload}>(), value.value)`;
  const decode = (c: Case, element: string) =>
    `${ref(c)}(json.decodeFromJsonElement(serializer<${c.payload}>(), ${element}))`;
  const unknown = (expr: string) =>
    `throw SerializationException("Unknown ${name} variant " + ${expr})`;

  const serialize: string[] = [];
  const deserialize: string[] = [];
  if (style === 'external') {
    // `"Name"` for a unit variant, `{ "Name": payload }` otherwise.
    for (const c of cases) {
      serialize.push(
        c.payload
          ? `            is ${ref(c)} -> JsonObject(mapOf(${kotlinString(c.variant.name)} to ${encode(c)}))`
          : `            ${ref(c)} -> JsonPrimitive(${kotlinString(c.variant.name)})`,
      );
    }
    const units = cases.filter((c) => !c.payload);
    if (units.length > 0) {
      deserialize.push(
        '        if (element is JsonPrimitive && element.isString) {',
        '            return when (element.content) {',
        ...units.map(
          (c) => `                ${kotlinString(c.variant.name)} -> ${ref(c)}`,
        ),
        `                else -> ${unknown('element.content')}`,
        '            }',
        '        }',
      );
    }
    deserialize.push(
      '        val (key, payload) = element.jsonObject.entries.singleOrNull()',
      `            ?: ${unknown('element')}`,
      '        return when (key) {',
      ...cases
        .filter((c) => c.payload)
        .map(
          (c) =>
            `            ${kotlinString(c.variant.name)} -> ${decode(c, 'payload')}`,
        ),
      `            else -> ${unknown('key')}`,
      '        }',
    );
  } else if (style === 'untagged') {
    // The payload alone, unit as `null`. Variants are tried in order, as serde does.
    for (const c of cases) {
      serialize.push(
        c.payload
          ? `            is ${ref(c)} -> ${encode(c)}`
          : `            ${ref(c)} -> JsonNull`,
      );
    }
    for (const c of cases) {
      deserialize.push(
        c.payload
          ? `        runCatching { ${decode(c, 'element')} }.getOrNull()?.let { return it }`
          : `        if (element is JsonNull) return ${ref(c)}`,
      );
    }
    deserialize.push(
      `        throw SerializationException("No ${name} variant matches " + element)`,
    );
  } else {
    // Internally tagged: `{ tag: "Name", ...payload fields }`; adjacently
    // tagged: `{ tag: "Name", content: payload }`.
    const tag = kotlinString(def.tag!);
    const content = def.content && kotlinString(def.content);
    for (const c of cases) {
      const tagEntry = `${tag} to JsonPrimitive(${kotlinString(c.variant.name)})`;
      if (!c.payload) {
        serialize.push(
          `            ${ref(c)} -> JsonObject(mapOf(${tagEntry}))`,
        );
      } else if (content) {
        serialize.push(
          `            is ${ref(c)} -> JsonObject(mapOf(${tagEntry}, ${content} to ${encode(c)}))`,
        );
      } else {
        serialize.push(
          `            is ${ref(c)} -> JsonObject(${encode(c)}.jsonObject + (${tagEntry}))`,
        );
      }
    }
    deserialize.push(
      '        val fields = element.jsonObject',
      `        val tag = fields[${tag}]?.jsonPrimitive?.content`,
      '        return when (tag) {',
    );
    for (const c of cases) {
      const payload = !c.payload
        ? ref(c)
        : content
          ? decode(c, `fields[${content}] ?: JsonNull`)
          : decode(c, `JsonObject(fields - ${tag})`);
      deserialize.push(
        `            ${kotlinString(c.variant.name)} -> ${payload}`,
      );
    }
    deserialize.push(`            else -> ${unknown('tag')}`, '        }');
  }

  lines.push(
    `internal object ${serializerName} : KSerializer<${name}> {`,
    '    override val descriptor: SerialDescriptor = JsonElement.serializer().descriptor',
    '',
    `    override fun serialize(encoder: Encoder, value: ${name}) {`,
    '        val json = (encoder as JsonEncoder).json',
    '        val element = when (value) {',
    ...serialize,
    '        }',
    '        encoder.encodeJsonElement(element)',
    '    }',
    '',
    `    override fun deserialize(decoder: Decoder): ${name} {`,
    '        val json = (decoder as JsonDecoder).json',
    '        val element = decoder.decodeJsonElement()',
    ...deserialize,
    '    }',
    '}',
  );
  return lines;
}

function clientClass(
  clientName: string,
  manifest: AbiManifest,
  types: NativeTypes,
): string[] {
  const lines = [
    '/** Typed calls to the contract. Views go through `query`, writes through `execute`. */',
    `class ${clientName}(private val transport: ContextContractCalling) {`,
  ];
  const argClasses: string[][] = [];
  manifest.methods.forEach((method, i) => {
    if (i > 0) lines.push('');
    lines.push(...clientMethod(method, manifest, types, argClasses));
  });
  for (const argClass of argClasses) lines.push('', ...argClass);
  lines.push(
    '',
    '    private companion object {',
    '        val json = Json { ignoreUnknownKeys = true }',
    '    }',
    '}',
  );
  return lines;
}

function clientMethod(
  method: AbiMethod,
  manifest: AbiManifest,
  types: NativeTypes,
  argClasses: string[][],
): string[] {
  const hint = upperCamel(method.name);
  const route = methodRoute(method);
  const params = method.params.map((param) => {
    const base = types.typeRef(param.type, `${hint}${upperCamel(param.name)}`);
    return {
      param,
      name: lowerCamel(param.name),
      type: param.nullable ? KOTLIN.optional(base) : base,
    };
  });

  let returnType: string | undefined;
  if (hasReturnValue(method)) {
    const base = types.typeRef(method.returns!, `${hint}Result`);
    returnType = method.returns_nullable ? KOTLIN.optional(base) : base;
  }

  const doc: string[] = [method.name];
  if (method.doc) doc.push('', method.doc);
  doc.push('', ...methodNotes(method, manifest));
  const tags = [
    ...params
      .filter((p) => p.param.doc)
      .map((p) => `@param ${p.name} ${docLines(p.param.doc!).join(' ')}`),
    method.returns_doc && `@return ${method.returns_doc}`,
  ].filter(Boolean) as string[];
  if (tags.length > 0) doc.push('', ...tags);

  const lines = docComment(doc.join('\n'), '    ');
  const signature = params
    .map(
      (p) =>
        `${ident(p.name)}: ${p.type}${p.type.endsWith('?') ? ' = null' : ''}`,
    )
    .join(', ');
  lines.push(
    `    suspend fun ${ident(lowerCamel(method.name))}(${signature})${returnType ? `: ${returnType}` : ''} {`,
  );

  let args = '"{}"';
  if (params.length > 0) {
    const argsName = `${hint}Args`;
    argClasses.push([
      '    @Serializable',
      `    private data class ${argsName}(`,
      ...params.flatMap((p) =>
        property(p.param.name, p.type, false, undefined, '        '),
      ),
      '    )',
    ]);
    // A null optional is left out of the object, as the web client leaves out
    // an undefined one: kotlinx does not encode a property at its default.
    const call = params.map((p) => ident(p.name)).join(', ');
    lines.push(
      `        val args = json.encodeToString(${argsName}.serializer(), ${argsName}(${call}))`,
    );
    args = 'args';
  }

  const send = `transport.${route}(${kotlinString(method.name)}, ${args})`;
  if (returnType) {
    lines.push(
      `        val response = ${send}`,
      `        return json.decodeFromString(serializer<${returnType}>(), response)`,
    );
  } else {
    lines.push(`        ${send}`);
  }
  lines.push('    }');
  return lines;
}

function tupleField(i: number): string {
  return TUPLE_FIELDS[i] ?? `item${i + 1}`;
}

// A Rust tuple, a JSON array of fixed length on the wire.
function tupleClass(arity: number): string[] {
  const params = Array.from({ length: arity }, (_, i) =>
    String.fromCharCode(65 + i),
  );
  const fields = params.map((_, i) => tupleField(i));
  const generics = params.join(', ');
  const name = `ContractTuple${arity}`;
  const serializers = params.map((p) => p.toLowerCase());
  return [
    `/** A ${arity}-element tuple, a JSON array on the wire. */`,
    `@Serializable(with = ${name}Serializer::class)`,
    `data class ${name}<${generics}>(${params.map((p, i) => `val ${fields[i]}: ${p}`).join(', ')})`,
    '',
    `internal class ${name}Serializer<${generics}>(`,
    ...params.map(
      (p, i) => `    private val ${serializers[i]}: KSerializer<${p}>,`,
    ),
    `) : KSerializer<${name}<${generics}>> {`,
    '    override val descriptor: SerialDescriptor = JsonArray.serializer().descriptor',
    '',
    `    override fun serialize(encoder: Encoder, value: ${name}<${generics}>) {`,
    '        val json = (encoder as JsonEncoder).json',
    '        encoder.encodeJsonElement(',
    '            JsonArray(',
    '                listOf(',
    ...fields.map(
      (f, i) =>
        `                    json.encodeToJsonElement(${serializers[i]}, value.${f}),`,
    ),
    '                ),',
    '            ),',
    '        )',
    '    }',
    '',
    `    override fun deserialize(decoder: Decoder): ${name}<${generics}> {`,
    '        val json = (decoder as JsonDecoder).json',
    '        val items = decoder.decodeJsonElement().jsonArray',
    `        if (items.size != ${arity}) throw SerializationException("Expected ${arity} elements, got " + items.size)`,
    `        return ${name}(`,
    ...fields.map(
      (_, i) =>
        `            json.decodeFromJsonElement(${serializers[i]}, items[${i}]),`,
    ),
    '        )',
    '    }',
    '}',
  ];
}
