const SWIFT: NativeSyntax = {
  scalars: {
    bool: 'Bool',
    i32: 'Int32',
    i64: 'Int64',
    u32: 'UInt32',
    u64: 'UInt64',
    f32: 'Float',
    f64: 'Double',
    string: 'String',
  },
  rustScalars: {
    String: 'String',
    bool: 'Bool',
    u8: 'UInt8',
    u16: 'UInt16',
    u32: 'UInt32',
    u64: 'UInt64',
    i8: 'Int8',
    i16: 'Int16',
    i32: 'Int32',
    i64: 'Int64',
    f32: 'Float',
    f64: 'Double',
  },
  unit: 'ContractUnit',
  // A JSON array of numbers, as the TS client sends bytes. `Data` would
  // encode as base64.
  bytes: '[UInt8]',
  fixedBytes: 'String',
  list: (item) => `[${item}]`,
  map: (key, value) => `[${key}: ${value}]`,
  optional: (type) => (type.endsWith('?') ? type : `${type}?`),
  tuple: (elements) =>
    `ContractTuple${elements.length}<${elements.join(', ')}>`,
};

// A name usable as a Swift identifier, backticked when it is a keyword.
function ident(name: string): string {
  return RESERVED.has(name) ? `\`${name}\`` : name;
}

function swiftString(text: string): string {
  const escaped = text
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t')
    .replace(
      /[\u0000-\u001f]/g,
      (ch) => `\\u{${ch.charCodeAt(0).toString(16)}}`,
    );
  return `"${escaped}"`;
}

function docComment(doc: string | undefined, indent: string): string[] {
  if (!doc) return [];
  return docLines(doc).map((line) =>
    line ? `${indent}/// ${line}` : `${indent}///`,
  );
}

/**
 * Generate a Swift client from a WASM-ABI v1 manifest
 * @param manifest - The parsed ABI manifest
 * @param clientName - The name of the generated client struct
 * @param transportModule - A module that declares `ContextContractCalling`
 *   (e.g. `MeroKit`); it is imported instead of declaring the protocol here
 * @returns Generated Swift source as a string
 */
export function generateSwiftClient(
  manifest: AbiManifest,
  clientName: string = 'Client',
  transportModule?: string,
): string {
  clientName = sanitizeClassName(clientName);
  const types = new NativeTypes(manifest, SWIFT);

  const typeBlocks: string[][] = [];
  for (const [name, def] of Object.entries(manifest.types)) {
    typeBlocks.push(typeDefinition(typeName(name), def, types));
  }
  const client = clientStruct(clientName, manifest, types);
  // Inline records are found while mapping, and may hold further inline records.
  for (let i = 0; i < types.inlineRecords.length; i++) {
    const { name, record } = types.inlineRecords[i];
    typeBlocks.push(struct(name, record.fields, record.doc, types));
  }

  const usesKeys = Object.values(manifest.types).some(
    (def) => def.kind === 'variant' && variantStyle(def) !== 'unit',
  );

  const lines: string[] = [BANNER, '', 'import Foundation'];
  if (transportModule) {
    lines.push(`import ${transportModule}`, '');
  } else {
    lines.push('', ...transportProtocol(), '');
  }
  lines.push(...client, '');
  lines.push('// MARK: - Types', '');
  for (const block of typeBlocks) lines.push(...block, '');
  const helpers = helperDeclarations(types, usesKeys);
  if (helpers.length > 0) {
    lines.push('// MARK: - Wire helpers', '', ...helpers);
  }
  return lines.join('\n').trimEnd() + '\n';
}

function transportProtocol(): string[] {
  return [
    '/// Carries one call to a context and returns the method’s JSON result.',
    '///',
    '/// `query` runs a view (a method the app declared `read_only`) and `execute`',
    '/// runs everything else. Both take the arguments as a JSON object and return',
    '/// the JSON the method produced.',
    'public protocol ContextContractCalling: Sendable {',
    '    func query(method: String, argsJSON: Data) async throws -> Data',
    '    func execute(method: String, argsJSON: Data) async throws -> Data',
    '}',
  ];
}

function typeDefinition(
  name: string,
  def: AbiTypeDef,
  types: NativeTypes,
): string[] {
  switch (def.kind) {
    case 'record':
      if (def.crdt_type && def.inner_type) {
        return [
          ...docComment(def.doc, ''),
          `public typealias ${name} = ${types.typeRef(def.inner_type, name)}`,
        ];
      }
      return struct(name, def.fields, def.doc, types);
    case 'variant':
      return enumeration(name, def, types);
    case 'alias': {
      const doc = [
        def.doc,
        def.pattern && `Values match \`${def.pattern}\` (not checked here).`,
      ]
        .filter(Boolean)
        .join('\n\n');
      return [
        ...docComment(doc, ''),
        `public typealias ${name} = ${types.typeRef(def.target, name)}`,
      ];
    }
    case 'bytes': {
      const size =
        'size' in def
          ? `${def.size} bytes, as the contract's own text (base58 or hex).`
          : undefined;
      return [
        ...docComment(size, ''),
        `public typealias ${name} = ${types.typeRef(def, name)}`,
      ];
    }
  }
}

function struct(
  name: string,
  fields: AbiField[],
  doc: string | undefined,
  types: NativeTypes,
): string[] {
  const props = fields.map((field) => {
    const base = types.typeRef(field.type, `${name}${upperCamel(field.name)}`);
    return {
      wire: field.name,
      name: lowerCamel(field.name),
      type: field.nullable ? SWIFT.optional(base) : base,
      doc: field.doc,
    };
  });

  const lines = [
    ...docComment(doc, ''),
    `public struct ${name}: ${CONFORMANCES} {`,
  ];
  for (const prop of props) {
    lines.push(
      ...docComment(prop.doc, '    '),
      `    public var ${ident(prop.name)}: ${prop.type}`,
    );
  }
  if (props.length > 0) lines.push('');

  const params = props.map(
    (prop) =>
      `${ident(prop.name)}: ${prop.type}${prop.type.endsWith('?') ? ' = nil' : ''}`,
  );
  lines.push(`    public init(${params.join(', ')}) {`);
  for (const prop of props) {
    lines.push(`        self.${ident(prop.name)} = ${ident(prop.name)}`);
  }
  lines.push('    }');

  if (props.some((prop) => prop.name !== prop.wire)) {
    lines.push('', '    enum CodingKeys: String, CodingKey {');
    for (const prop of props) {
      lines.push(
        prop.name === prop.wire
          ? `        case ${ident(prop.name)}`
          : `        case ${ident(prop.name)} = ${swiftString(prop.wire)}`,
      );
    }
    lines.push('    }');
  }
  lines.push('}');
  return lines;
}

interface Case {
  variant: AbiVariant;
  name: string;
  payload?: string;
}

function enumeration(
  name: string,
  def: AbiVariantDef,
  types: NativeTypes,
): string[] {
  const style = variantStyle(def);
  const cases: Case[] = def.variants.map((variant) => ({
    variant,
    name: lowerCamel(variant.name),
    payload:
      variant.payload && !NativeTypes.isUnit(variant.payload)
        ? types.typeRef(variant.payload, `${name}${upperCamel(variant.name)}`)
        : undefined,
  }));

  const lines = [...docComment(def.doc, '')];
  if (style === 'unit') {
    // serde writes a payload-free enum as the bare variant name.
    lines.push(`public enum ${name}: String, ${CONFORMANCES}, CaseIterable {`);
    for (const c of cases) {
      lines.push(
        ...docComment(c.variant.doc, '    '),
        `    case ${ident(c.name)} = ${swiftString(c.variant.name)}`,
      );
    }
    lines.push('}');
    return lines;
  }

  // indirect: a payload may name this enum again.
  lines.push(`public indirect enum ${name}: ${CONFORMANCES} {`);
  for (const c of cases) {
    lines.push(
      ...docComment(c.variant.doc, '    '),
      c.payload
        ? `    case ${ident(c.name)}(${c.payload})`
        : `    case ${ident(c.name)}`,
    );
  }
  lines.push('');
  const unknown = (expr: string) =>
    `contractUnknownVariant(${swiftString(name)}, ${expr}, decoder.codingPath)`;

  if (style === 'external') {
    lines.push(...externalCoding(cases, unknown));
  } else if (style === 'untagged') {
    lines.push(...untaggedCoding(name, cases));
  } else {
    lines.push(...taggedCoding(def, cases, unknown));
  }
  lines.push('}');
  return lines;
}

// `"Name"` for a unit variant, `{ "Name": payload }` otherwise.
function externalCoding(
  cases: Case[],
  unknown: (expr: string) => string,
): string[] {
  const units = cases.filter((c) => !c.payload);
  const payloads = cases.filter((c) => c.payload);
  const lines = ['    public init(from decoder: any Decoder) throws {'];
  if (units.length > 0) {
    lines.push(
      '        if let name = try? decoder.singleValueContainer().decode(String.self) {',
      '            switch name {',
      ...units.map(
        (c) =>
          `            case ${swiftString(c.variant.name)}: self = .${ident(c.name)}`,
      ),
      `            default: throw ${unknown('name')}`,
      '            }',
      '            return',
      '        }',
    );
  }
  lines.push(
    '        let container = try decoder.container(keyedBy: ContractCodingKey.self)',
    '        guard let key = container.allKeys.first else {',
    `            throw ${unknown('""')}`,
    '        }',
    '        switch key.stringValue {',
    ...payloads.map(
      (c) =>
        `        case ${swiftString(c.variant.name)}: self = .${ident(c.name)}(try container.decode(${c.payload}.self, forKey: key))`,
    ),
    `        default: throw ${unknown('key.stringValue')}`,
    '        }',
    '    }',
    '',
    '    public func encode(to encoder: any Encoder) throws {',
    '        switch self {',
  );
  for (const c of cases) {
    if (c.payload) {
      lines.push(
        `        case .${ident(c.name)}(let value):`,
        '            var container = encoder.container(keyedBy: ContractCodingKey.self)',
        `            try container.encode(value, forKey: ContractCodingKey(${swiftString(c.variant.name)}))`,
      );
    } else {
      lines.push(
        `        case .${ident(c.name)}:`,
        '            var container = encoder.singleValueContainer()',
        `            try container.encode(${swiftString(c.variant.name)})`,
      );
    }
  }
  lines.push('        }', '    }');
  return lines;
}

// Internally tagged: `{ tag: "Name", ...payload fields }`; adjacently tagged:
// `{ tag: "Name", content: payload }`.
function taggedCoding(
  def: AbiVariantDef,
  cases: Case[],
  unknown: (expr: string) => string,
): string[] {
  const tagKey = `ContractCodingKey(${swiftString(def.tag!)})`;
  const contentKey = def.content
    ? `ContractCodingKey(${swiftString(def.content)})`
    : undefined;
  const read = (payload: string) =>
    contentKey
      ? `try container.decode(${payload}.self, forKey: ${contentKey})`
      : `try ${payload}(from: decoder)`;

  const lines = [
    '    public init(from decoder: any Decoder) throws {',
    '        let container = try decoder.container(keyedBy: ContractCodingKey.self)',
    `        let tag = try container.decode(String.self, forKey: ${tagKey})`,
    '        switch tag {',
    ...cases.map((c) =>
      c.payload
        ? `        case ${swiftString(c.variant.name)}: self = .${ident(c.name)}(${read(c.payload)})`
        : `        case ${swiftString(c.variant.name)}: self = .${ident(c.name)}`,
    ),
    `        default: throw ${unknown('tag')}`,
    '        }',
    '    }',
    '',
    '    public func encode(to encoder: any Encoder) throws {',
    '        var container = encoder.container(keyedBy: ContractCodingKey.self)',
    '        switch self {',
  ];
  for (const c of cases) {
    const tag = `try container.encode(${swiftString(c.variant.name)}, forKey: ${tagKey})`;
    if (!c.payload) {
      lines.push(`        case .${ident(c.name)}:`, `            ${tag}`);
    } else if (contentKey) {
      lines.push(
        `        case .${ident(c.name)}(let value):`,
        `            ${tag}`,
        `            try container.encode(value, forKey: ${contentKey})`,
      );
    } else {
      // The payload's own fields share the object with the tag.
      lines.push(
        `        case .${ident(c.name)}(let value):`,
        '            try value.encode(to: encoder)',
        `            ${tag}`,
      );
    }
  }
  lines.push('        }', '    }');
  return lines;
}

// The payload alone, unit as `null`. Decoding tries the variants in order, as serde does.
function untaggedCoding(name: string, cases: Case[]): string[] {
  const lines = [
    '    public init(from decoder: any Decoder) throws {',
    '        let container = try decoder.singleValueContainer()',
  ];
  for (const c of cases) {
    if (c.payload) {
      lines.push(
        `        if let value = try? container.decode(${c.payload}.self) {`,
        `            self = .${ident(c.name)}(value)`,
        '            return',
        '        }',
      );
    } else {
      lines.push(
        '        if container.decodeNil() {',
        `            self = .${ident(c.name)}`,
        '            return',
        '        }',
      );
    }
  }
  lines.push(
    `        throw DecodingError.dataCorruptedError(in: container, debugDescription: ${swiftString(`No ${name} variant matches`)})`,
    '    }',
    '',
    '    public func encode(to encoder: any Encoder) throws {',
    '        var container = encoder.singleValueContainer()',
    '        switch self {',
  );
  for (const c of cases) {
    lines.push(
      c.payload
        ? `        case .${ident(c.name)}(let value): try container.encode(value)`
        : `        case .${ident(c.name)}: try container.encodeNil()`,
    );
  }
  lines.push('        }', '    }');
  return lines;
}

function clientStruct(
  clientName: string,
  manifest: AbiManifest,
  types: NativeTypes,
): string[] {
  const lines = [
    `/// Typed calls to the contract. Views go through \`query\`, writes through \`execute\`.`,
    `public struct ${clientName}: Sendable {`,
    '    public let transport: any ContextContractCalling',
    '',
    '    public init(transport: any ContextContractCalling) {',
    '        self.transport = transport',
    '    }',
  ];
  const argStructs: string[][] = [];
  for (const method of manifest.methods) {
    lines.push('', ...clientMethod(method, manifest, types, argStructs));
  }
  for (const argStruct of argStructs) lines.push('', ...argStruct);
  lines.push('}');
  return lines;
}

function clientMethod(
  method: AbiMethod,
  manifest: AbiManifest,
  types: NativeTypes,
  argStructs: string[][],
): string[] {
  const methodName = ident(lowerCamel(method.name));
  const hint = upperCamel(method.name);
  const route = methodRoute(method);
  const params = method.params.map((param) => {
    const base = types.typeRef(param.type, `${hint}${upperCamel(param.name)}`);
    return {
      wire: param.name,
      name: lowerCamel(param.name),
      type: param.nullable ? SWIFT.optional(base) : base,
      doc: param.doc,
    };
  });

  let returnType: string | undefined;
  if (hasReturnValue(method)) {
    const base = types.typeRef(method.returns!, `${hint}Result`);
    returnType = method.returns_nullable ? SWIFT.optional(base) : base;
  }

  const doc: string[] = [method.name];
  if (method.doc) doc.push('', method.doc);
  doc.push('', ...methodNotes(method, manifest));
  const paramDocs = params.filter((p) => p.doc);
  if (paramDocs.length > 0) {
    doc.push('', '- Parameters:');
    for (const p of paramDocs) {
      doc.push(`  - ${p.name}: ${docLines(p.doc!).join(' ')}`);
    }
  }
  if (method.returns_doc) doc.push(`- Returns: ${method.returns_doc}`);

  const lines = docComment(doc.join('\n'), '    ');
  if (returnType && route === 'execute') {
    lines.push('    @discardableResult');
  }
  const signature = params
    .map(
      (p) =>
        `${ident(p.name)}: ${p.type}${p.type.endsWith('?') ? ' = nil' : ''}`,
    )
    .join(', ');
  lines.push(
    `    public func ${methodName}(${signature}) async throws${returnType ? ` -> ${returnType}` : ''} {`,
  );

  let args = 'Data("{}".utf8)';
  if (params.length > 0) {
    const argsName = `${hint}Args`;
    const structLines = [`    private struct ${argsName}: Encodable {`];
    for (const p of params) {
      structLines.push(`        let ${ident(p.name)}: ${p.type}`);
    }
    if (params.some((p) => p.name !== p.wire)) {
      structLines.push('', '        enum CodingKeys: String, CodingKey {');
      for (const p of params) {
        structLines.push(
          p.name === p.wire
            ? `            case ${ident(p.name)}`
            : `            case ${ident(p.name)} = ${swiftString(p.wire)}`,
        );
      }
      structLines.push('        }');
    }
    structLines.push('    }');
    argStructs.push(structLines);
    // A nil optional is left out of the object (`encodeIfPresent`), as the
    // web client leaves out an undefined one.
    const call = params
      .map((p) => `${ident(p.name)}: ${ident(p.name)}`)
      .join(', ');
    lines.push(
      `        let args = try JSONEncoder().encode(${argsName}(${call}))`,
    );
    args = 'args';
  }

  const send = `try await transport.${route}(method: ${swiftString(method.name)}, argsJSON: ${args})`;
  if (returnType) {
    lines.push(
      `        let response = ${send}`,
      `        return try JSONDecoder().decode(${returnType}.self, from: response)`,
    );
  } else {
    lines.push(`        _ = ${send}`);
  }
  lines.push('    }');
  return lines;
}

function helperDeclarations(types: NativeTypes, usesKeys: boolean): string[] {
  const lines: string[] = [];
  if (types.usesUnit) {
    lines.push(
      '/// serde’s unit value, `null` on the wire.',
      `public struct ContractUnit: ${CONFORMANCES} {`,
      '    public init() {}',
      '',
      '    public init(from decoder: any Decoder) throws {',
      '        _ = try decoder.singleValueContainer()',
      '    }',
      '',
      '    public func encode(to encoder: any Encoder) throws {',
      '        var container = encoder.singleValueContainer()',
      '        try container.encodeNil()',
      '    }',
      '}',
      '',
    );
  }
  for (const arity of [...types.tupleArities].sort((a, b) => a - b)) {
    lines.push(...tupleStruct(arity), '');
  }
  if (usesKeys) {
    lines.push(
      'fileprivate struct ContractCodingKey: CodingKey {',
      '    let stringValue: String',
      '    var intValue: Int? { nil }',
      '',
      '    init(_ stringValue: String) { self.stringValue = stringValue }',
      '    init?(stringValue: String) { self.stringValue = stringValue }',
      '    init?(intValue: Int) { nil }',
      '}',
      '',
      'fileprivate func contractUnknownVariant(_ type: String, _ name: String, _ codingPath: [any CodingKey]) -> DecodingError {',
      '    DecodingError.dataCorrupted(.init(codingPath: codingPath, debugDescription: "Unknown \\(type) variant \\"\\(name)\\""))',
      '}',
      '',
    );
  }
  return lines;
}

function tupleField(i: number): string {
  return TUPLE_FIELDS[i] ?? `item${i + 1}`;
}

// A Rust tuple, a JSON array of fixed length on the wire.
function tupleStruct(arity: number): string[] {
  const params = Array.from({ length: arity }, (_, i) =>
    String.fromCharCode(65 + i),
  );
  const fields = params.map((_, i) => tupleField(i));
  return [
    `/// A ${arity}-element tuple, a JSON array on the wire.`,
    `public struct ContractTuple${arity}<${params.map((p) => `${p}: ${CONFORMANCES.replace(/, /g, ' & ')}`).join(', ')}>: ${CONFORMANCES} {`,
    ...params.map((p, i) => `    public var ${fields[i]}: ${p}`),
    '',
    `    public init(${params.map((p, i) => `_ ${fields[i]}: ${p}`).join(', ')}) {`,
    ...fields.map((f) => `        self.${f} = ${f}`),
    '    }',
    '',
    '    public init(from decoder: any Decoder) throws {',
    '        var container = try decoder.unkeyedContainer()',
    ...params.map(
      (p, i) => `        ${fields[i]} = try container.decode(${p}.self)`,
    ),
    '    }',
    '',
    '    public func encode(to encoder: any Encoder) throws {',
    '        var container = encoder.unkeyedContainer()',
    ...fields.map((f) => `        try container.encode(${f})`),
    '    }',
    '}',
  ];
}
